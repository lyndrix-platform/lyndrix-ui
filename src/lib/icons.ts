export function getPluginIcon(iconName: string | null | undefined): LucideIcon {
  if (!iconName) return Puzzle
  const key = iconName.trim().toLowerCase().replace(/[\s-]+/g, '_')
  return iconMap[key] ?? Puzzle
}
